//! The dataset manifest: what was written, and under what conditions.
//!
//! The manifest is the honest record of a dataset. It says which file was
//! written, how many rows it holds, how big it is, which columns it has and
//! -- importantly -- that it is TPC-H-*shaped* synthetic data and not the
//! official TPC-H SF-1 file. A benchmark number without that note is a
//! benchmark number that will be misquoted.

use crate::DatasetError;
use serde::{Deserialize, Serialize};
use std::io::ErrorKind;
use std::path::{Path, PathBuf};

/// The provenance note written into every manifest.
///
/// The dataset is TPC-H-shaped, not the official TPC-H SF-1 file. The
/// distributions are approximated, the dates are UTF-8 strings rather than
/// a date type, and every value is drawn from a seeded PRNG.
pub const PROVENANCE: &str = "TPC-H-shaped synthetic lineitem generated by columnar-testdata. \
This is NOT the official TPC-H SF-1 file: the distributions are approximated, the date columns are \
UTF-8 strings in YYYY-MM-DD form rather than a date type, and every value is drawn from a seeded \
splitmix64/xoshiro256** stream.";

/// The suffix appended to the dataset path to name its manifest.
pub const MANIFEST_SUFFIX: &str = ".manifest.json";

/// What was written, and under what conditions.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DatasetManifest {
    /// Absolute path of the written Parquet file.
    pub path: String,
    /// Number of rows written.
    pub rows: u64,
    /// Size of the file in bytes.
    pub bytes: u64,
    /// Column names in schema order.
    pub columns: Vec<String>,
    /// The scale factor used.
    pub scale_factor: u32,
    /// The seed used.
    pub seed: u64,
    /// The null rate used.
    pub null_rate: f64,
    /// Free-form note stating the dataset is TPC-H-shaped, not the official file.
    pub provenance: String,
    /// Version of the generator that produced it.
    pub generator_version: String,
}

impl DatasetManifest {
    /// Writes the manifest as JSON next to the dataset, at `<output>.manifest.json`.
    ///
    /// # Errors
    ///
    /// Returns [`DatasetError::Io`] if the manifest cannot be written.
    pub fn write_json(&self) -> Result<(), DatasetError> {
        let path = manifest_path(Path::new(&self.path));
        let json = serde_json::to_string_pretty(self).map_err(|error| {
            DatasetError::Io(std::io::Error::new(
                ErrorKind::InvalidData,
                format!("manifest json: {error}"),
            ))
        })?;
        std::fs::write(path, json)?;
        Ok(())
    }

    /// Reads a manifest back from `<path>.manifest.json`.
    ///
    /// # Errors
    ///
    /// Returns [`DatasetError::Io`] if the manifest cannot be read or does
    /// not hold a valid manifest.
    pub fn read_json(path: &Path) -> Result<DatasetManifest, DatasetError> {
        let manifest_path = manifest_path(path);
        let json = std::fs::read_to_string(&manifest_path)?;
        serde_json::from_str(&json).map_err(|error| {
            DatasetError::Io(std::io::Error::new(
                ErrorKind::InvalidData,
                format!("manifest json: {error}"),
            ))
        })
    }
}

/// The path of the manifest that belongs to a dataset file.
///
/// The manifest sits next to the dataset and is named after it, so
/// `lineitem.parquet` and `lineitem.parquet.manifest.json` are a pair.
#[must_use]
pub fn manifest_path(dataset: &Path) -> PathBuf {
    let mut name = dataset.as_os_str().to_os_string();
    name.push(MANIFEST_SUFFIX);
    PathBuf::from(name)
}
