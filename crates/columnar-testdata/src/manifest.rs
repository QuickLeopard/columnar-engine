//! The dataset manifest: what was written, and under what conditions.
//!
//! The manifest is the honest record of a dataset. It says which file was
//! written, how many rows it holds, how big it is, which columns it has and
//! -- importantly -- that it is TPC-H-*shaped* synthetic data and not the
//! official TPC-H SF-1 file. A benchmark number without that note is a
//! benchmark number that will be misquoted.
//!
//! The dataset holds two tables, and the manifest records both: the flat
//! fields describe the file the manifest sits beside, and the table list
//! describes the whole dataset. The join's key space and match rate are
//! recorded too, because the published join figure depends on them.

use crate::DatasetError;
use serde::{Deserialize, Serialize};
use std::io::ErrorKind;
use std::path::{Path, PathBuf};

/// The provenance note written into every manifest.
///
/// The dataset is TPC-H-shaped, not the official TPC-H SF-1 file. The
/// distributions are approximated, the dates are UTF-8 strings rather than
/// a date type, and every value is drawn from a seeded PRNG.
pub const PROVENANCE: &str = "TPC-H-shaped synthetic lineitem generated by columnar-testdata. \
This is NOT the official TPC-H SF-1 file: the distributions are approximated, the date columns are \
UTF-8 strings in YYYY-MM-DD form rather than a date type, and every value is drawn from a seeded \
splitmix64/xoshiro256** stream.";

/// The provenance note written into the `orders` manifest.
///
/// The same caveat as [`PROVENANCE`], for the second table.
pub const ORDERS_PROVENANCE: &str =
    "TPC-H-shaped synthetic orders generated by columnar-testdata. \
This is NOT the official TPC-H SF-1 file: the distributions are approximated, the date columns are \
UTF-8 strings in YYYY-MM-DD form rather than a date type, and every value is drawn from a seeded \
splitmix64/xoshiro256** stream.";

/// The name of the `lineitem` table.
pub const LINEITEM_TABLE: &str = "lineitem";

/// The name of the `orders` table.
pub const ORDERS_TABLE: &str = "orders";

/// The suffix appended to the dataset path to name its manifest.
pub const MANIFEST_SUFFIX: &str = ".manifest.json";

/// The key space a join is drawn over, and what that join is expected to do.
///
/// The manifest states it because the published join figure depends on it:
/// a join whose two sides do not share a key space is empty, and a join
/// over a shared one is a fraction of the rows.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct KeySpace {
    /// The join key column on the probe side.
    pub probe_column: String,
    /// The join key column on the build side.
    pub build_column: String,
    /// The smallest key in the space.
    pub min: i64,
    /// The largest key in the space.
    pub max: i64,
    /// The number of distinct keys the build side holds.
    pub distinct_keys: u64,
    /// The expected fraction of the probe side's rows that find a partner.
    ///
    /// This is the number the published join figure depends on. The build
    /// side's keys are distinct, so a probe row finds **at most one**
    /// partner, and the join produces this fraction of the probe side's
    /// rows -- before any predicate on the build side, which can only
    /// lower it.
    pub expected_match_rate: f64,
}

impl KeySpace {
    /// The key space of the `lineitem` and `orders` tables of a dataset.
    ///
    /// The two sides share one space: `l_orderkey` and `o_orderkey` are
    /// both drawn from `[1, lineitem_rows]`, and the `orders` keys are
    /// distinct. So a `lineitem` row finds a partner with probability
    /// `orders_rows / lineitem_rows` -- a quarter at every scale factor,
    /// because `orders` is a quarter of `lineitem`.
    #[must_use]
    pub fn join(lineitem_rows: u64, orders_rows: u64) -> Self {
        let expected_match_rate = if lineitem_rows == 0 {
            0.0
        } else {
            // The counts are far below 2^53, so the conversion to a double
            // is exact and the rate is the ratio of the two counts.
            #[allow(clippy::cast_precision_loss)]
            let ratio = orders_rows as f64 / lineitem_rows as f64;
            ratio.min(1.0)
        };

        Self {
            probe_column: "l_orderkey".to_string(),
            build_column: "o_orderkey".to_string(),
            // An empty dataset has no key space, and says so: the range is
            // empty rather than a range that runs backwards.
            min: i64::from(lineitem_rows > 0),
            max: i64::try_from(lineitem_rows).unwrap_or(i64::MAX),
            distinct_keys: orders_rows,
            expected_match_rate,
        }
    }
}

/// One table of the dataset.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TableRecord {
    /// The table's name: `lineitem` or `orders`.
    pub name: String,
    /// Absolute path of the file the table was written to.
    pub path: String,
    /// Number of rows written.
    pub rows: u64,
    /// Size of the file in bytes.
    pub bytes: u64,
    /// Column names in schema order.
    pub columns: Vec<String>,
}

impl TableRecord {
    /// The record of the table a manifest describes.
    #[must_use]
    pub fn of(manifest: &DatasetManifest) -> Self {
        Self {
            name: manifest.table.clone(),
            path: manifest.path.clone(),
            rows: manifest.rows,
            bytes: manifest.bytes,
            columns: manifest.columns.clone(),
        }
    }
}

/// What was written, and under what conditions.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DatasetManifest {
    /// Absolute path of the written Parquet file.
    pub path: String,
    /// Number of rows written.
    pub rows: u64,
    /// Size of the file in bytes.
    pub bytes: u64,
    /// Column names in schema order.
    pub columns: Vec<String>,
    /// The scale factor used.
    pub scale_factor: u32,
    /// The seed used.
    pub seed: u64,
    /// The null rate used.
    pub null_rate: f64,
    /// The number of rows written per Parquet row group.
    ///
    /// This is the knob the parallelism cap hangs on: the read splits the
    /// file's **row groups** across the workers, so the number of workers is
    /// bounded by the number of row groups, and the number of row groups is
    /// this number and the row count.
    #[serde(default)]
    pub row_group_rows: usize,
    /// How many row groups were actually written.
    #[serde(default)]
    pub row_groups: u64,
    /// Free-form note stating the dataset is TPC-H-shaped, not the official file.
    pub provenance: String,
    /// Version of the generator that produced it.
    pub generator_version: String,
    /// The table this file holds: `lineitem` or `orders`.
    ///
    /// Empty in a manifest written before the dataset had a second table.
    #[serde(default)]
    pub table: String,
    /// Every table in the dataset, in the order the dataset writes them.
    ///
    /// The first entry is the table this file holds. A manifest written
    /// before the dataset had a second table carries one entry.
    #[serde(default)]
    pub tables: Vec<TableRecord>,
    /// The key space of the join between the dataset's tables.
    ///
    /// Absent in a manifest written before the dataset had a second table.
    #[serde(default)]
    pub key_space: Option<KeySpace>,
}

impl DatasetManifest {
    /// Writes the manifest as JSON next to the dataset, at `<output>.manifest.json`.
    ///
    /// # Errors
    ///
    /// Returns [`DatasetError::Io`] if the manifest cannot be written.
    pub fn write_json(&self) -> Result<(), DatasetError> {
        let path = manifest_path(Path::new(&self.path));
        let json = serde_json::to_string_pretty(self).map_err(|error| {
            DatasetError::Io(std::io::Error::new(
                ErrorKind::InvalidData,
                format!("manifest json: {error}"),
            ))
        })?;
        std::fs::write(path, json)?;
        Ok(())
    }

    /// Reads a manifest back from `<path>.manifest.json`.
    ///
    /// # Errors
    ///
    /// Returns [`DatasetError::Io`] if the manifest cannot be read or does
    /// not hold a valid manifest.
    pub fn read_json(path: &Path) -> Result<DatasetManifest, DatasetError> {
        let manifest_path = manifest_path(path);
        let json = std::fs::read_to_string(&manifest_path)?;
        serde_json::from_str(&json).map_err(|error| {
            DatasetError::Io(std::io::Error::new(
                ErrorKind::InvalidData,
                format!("manifest json: {error}"),
            ))
        })
    }
}

/// The path of the manifest that belongs to a dataset file.
///
/// The manifest sits next to the dataset and is named after it, so
/// `lineitem.parquet` and `lineitem.parquet.manifest.json` are a pair.
#[must_use]
pub fn manifest_path(dataset: &Path) -> PathBuf {
    let mut name = dataset.as_os_str().to_os_string();
    name.push(MANIFEST_SUFFIX);
    PathBuf::from(name)
}
